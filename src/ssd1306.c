static void cmd(ssd1306_t *p, uint8_t c) {
    uint8_t b[2] = {0x00, c};
    i2c_write_blocking(p->i2c_port, p->address, b, 2, false);
}

void ssd1306_init(ssd1306_t *p, uint8_t w, uint8_t h, uint8_t addr, i2c_inst_t *i2c) {
    p->width = w; p->height = h; p->address = addr; p->i2c_port = i2c;
    p->pages = h / 8;
    memset(p->buffer, 0, sizeof(p->buffer));
    p->buffer[0] = 0x40;

    uint8_t cmds[] = {0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40, 0x8D, 0x14, 0x20, 0x02, 0xA1, 0xC8, 0xDA, 0x12, 0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF};
    for (int i = 0; i < (int)sizeof(cmds); i++) cmd(p, cmds[i]);
}

void ssd1306_fill(ssd1306_t *p, bool color) {
    memset(p->buffer + 1, color ? 0xFF : 0x00, 1024);
}

void ssd1306_draw_string(ssd1306_t *p, const char *str, uint8_t x, uint8_t y) {
    uint8_t page = y / 8;
    if (page >= p->pages) return;
    while (*str) {
        uint8_t c = (uint8_t)*str++;
        int idx = (c - 32) * 5;
        for (int i = 0; i < 5; i++) {
            if (x < 128) p->buffer[1 + x + (page * 128)] = font[idx + i];
            x++;
        }
        x += 2;
    }
}

void ssd1306_show(ssd1306_t *p) {
    for (uint8_t i = 0; i < p->pages; i++) {
        cmd(p, 0xB0 + i); cmd(p, 0x00); cmd(p, 0x10);
        uint8_t temp[129];
        temp[0] = 0x40;
        memcpy(temp + 1, p->buffer + 1 + (i * 128), 128);
        i2c_write_blocking(p->i2c_port, p->address, temp, 129, false);
    }
}